import { createCanvas, loadImage } from "@napi-rs/canvas";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { format } from "prettier";
const root = new URL("../", import.meta.url);
const definitions = {
  maple: ["data/world-pack/maple.png", [96, 0, 32, 48], [2, 6]],
  sapling: ["data/world-pack/maple.png", [64, 0, 32, 48], [2, 6]],
  seedling: ["data/world-pack/maple.png", [32, 32, 32, 16], [2, 6]],
  stump: ["data/world-pack/maple.png", [128, 32, 32, 16], [1, 2, 3, 6]],
  forest: ["public/forest.png", null, [2, 6]],
  jungle: ["public/jungle.png", null, [1]],
  acacia: ["public/savanna.png", null, [4]],
  palm: ["public/beach.png", null, [1, 5]],
  snowPine: ["public/snow.png", null, [3, 8]],
  pine: ["public/snow.png", null, [3, 8]],
  grass: ["data/world-pack/grass.png", [64, 48, 16, 16], [1, 2, 4, 6]],
};
await mkdir(new URL("public/world-life/", root), { recursive: true });
const manifest = {
  version: 1,
  source:
    "Official user supplied Farm RPG FREE 16x16 pack and repository biome PNGs",
  sprites: {},
  sheets: {},
};
for (const [id, [path, crop, biomes]] of Object.entries(definitions)) {
  const bytes = await readFile(new URL(path, root)),
    image = await loadImage(bytes);
  const [sx, sy, w, h] = crop ?? [0, 0, image.width, image.height];
  const temp = createCanvas(w, h),
    ctx = temp.getContext("2d");
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(image, sx, sy, w, h, 0, 0, w, h);
  const pixels = ctx.getImageData(0, 0, w, h);
  let x0 = w,
    y0 = h,
    x1 = 0,
    y1 = 0;
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) {
      const k = (y * w + x) * 4;
      if (!pixels.data[k + 3]) continue;
      x0 = Math.min(x0, x);
      y0 = Math.min(y0, y);
      x1 = Math.max(x1, x);
      y1 = Math.max(y1, y);
      if (
        id === "pine" &&
        Math.min(...pixels.data.slice(k, k + 3)) > 100 &&
        Math.max(...pixels.data.slice(k, k + 3)) -
          Math.min(...pixels.data.slice(k, k + 3)) <
          65
      ) {
        const value = pixels.data[k];
        pixels.data.set(
          value > 210
            ? [122, 160, 111]
            : value > 165
              ? [81, 124, 90]
              : [55, 94, 76],
          k,
        );
      }
    }
  ctx.putImageData(pixels, 0, 0);
  const out = createCanvas(x1 - x0 + 1, y1 - y0 + 1);
  out
    .getContext("2d")
    .drawImage(
      temp,
      x0,
      y0,
      out.width,
      out.height,
      0,
      0,
      out.width,
      out.height,
    );
  const png = out.toBuffer("image/png");
  await writeFile(new URL(`public/world-life/${id}.png`, root), png);
  manifest.sprites[id] = {
    source: path,
    sourceSha256: createHash("sha256").update(bytes).digest("hex"),
    crop: [sx + x0, sy + y0, out.width, out.height],
    width: out.width,
    height: out.height,
    pivot: [Math.floor(out.width / 2), out.height - 1],
    biomes,
    mirror: false,
    sha256: createHash("sha256").update(png).digest("hex"),
    palette:
      id === "pine"
        ? "Snow highlights replaced by three foliage colors; original silhouette retained"
        : null,
  };
}
for (const id of [
  "chick",
  "chicken-blonde",
  "chicken-red",
  "cow-female",
  "cow-male",
  "crops",
  "grass",
]) {
  const bytes = await readFile(new URL(`data/world-pack/${id}.png`, root));
  await writeFile(new URL(`public/world-life/${id}-sheet.png`, root), bytes);
  const animal = id.startsWith("cow") || id.startsWith("chick");
  manifest.sheets[id] = {
    source: `data/world-pack/${id}.png`,
    sha256: createHash("sha256").update(bytes).digest("hex"),
    frameWidth: id.startsWith("cow") ? 32 : 16,
    frameHeight: id.startsWith("cow") ? 32 : 16,
    frames: animal ? 4 : null,
    sideRow: 0,
    pivot: id.startsWith("cow") ? [16, 30] : [8, 15],
    mirror: animal,
  };
}
await writeFile(
  new URL("public/world-life/source.json", root),
  JSON.stringify(manifest, null, 2) + "\n",
);
// Compile the same dimensions into the runtime catalog, avoiding asynchronous JSON in workers.
await writeFile(
  new URL("src/environment/asset-data.ts", root),
  await format(
    "// Generated by scripts/prepare-world-life.mjs from the official assets.\nexport const ASSET_DATA = " +
      JSON.stringify(
        Object.fromEntries(
          Object.entries(manifest.sprites).map(([id, s]) => [
            id,
            {
              width: s.width,
              height: s.height,
              biomes: s.biomes,
              mirror: s.mirror,
            },
          ]),
        ),
        null,
        2,
      ) +
      " as const;\n",
    { parser: "typescript" },
  ),
);
console.log(
  "Prepared official world-life sprites, sheets and provenance manifest",
);
